// Regenerates lib/mcp/docs/bundled_docs.dart from the MIGRATION.md files of the
// sibling bond-core and flutter-bond checkouts, so `bond mcp` can serve them
// without network access (they are not part of the published package archives).
//
//   dart run tool/sync_mcp_docs.dart [../bond-core] [../flutter-bond]
//
// Run it before every bond_cli release.
import 'dart:io';

void main(List<String> args) {
  final bondCore = args.isNotEmpty ? args[0] : '../bond-core';
  final template = args.length > 1 ? args[1] : '../flutter-bond';

  final docs = {
    'packagesMigrationGuide': File('$bondCore/MIGRATION.md'),
    'templateMigrationGuide': File('$template/MIGRATION.md'),
  };

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/sync_mcp_docs.dart - do not edit by hand.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln();
  for (final MapEntry(key: name, value: file) in docs.entries) {
    final text = file.readAsStringSync().trimRight();
    if (text.contains("'''")) {
      stderr.writeln("${file.path} contains ''' and can't be embedded.");
      exitCode = 1;
      return;
    }
    out
      ..writeln(
        '/// Copy of `${file.uri.pathSegments.last}` from ${file.parent.uri.pathSegments.where((s) => s.isNotEmpty).last}.',
      )
      ..writeln("const $name = r'''")
      ..writeln(text)
      ..writeln("''';")
      ..writeln();
  }
  File('lib/mcp/docs/bundled_docs.dart').writeAsStringSync(out.toString());
  stdout.writeln('Wrote lib/mcp/docs/bundled_docs.dart');
}
